// Builds the WebAssembly module from rust/ and writes it, with its
// JavaScript glue, to src/native/. The module's bytes are embedded as base64
// so that the package loads the same way in every runtime, with no file or
// network access at load time.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const rust = join(root, "rust");
const out = join(root, "src", "native");
const target = "wasm32-unknown-unknown";

function run(command, args, options = {}) {
  return execFileSync(command, args, { stdio: ["ignore", "pipe", "inherit"], ...options })
    .toString()
    .trim();
}

// The command that post-processes the module must be the version of the
// wasm-bindgen crate the module was compiled against.
const pinned = /^wasm-bindgen = "=([0-9.]+)"$/m.exec(
  readFileSync(join(rust, "Cargo.toml"), "utf8"),
)?.[1];
if (!pinned) {
  throw new Error("rust/Cargo.toml does not pin wasm-bindgen to an exact version");
}
let installed;
try {
  installed = run("wasm-bindgen", ["--version"]).split(" ")[1];
} catch {
  throw new Error(
    `wasm-bindgen is not installed: cargo install wasm-bindgen-cli --version ${pinned} --locked`,
  );
}
if (installed !== pinned) {
  throw new Error(
    `wasm-bindgen ${installed} is installed, and the module needs ${pinned}: ` +
      `cargo install wasm-bindgen-cli --version ${pinned} --locked`,
  );
}

execFileSync("cargo", ["build", "--release", "--locked", "--target", target], {
  cwd: rust,
  stdio: "inherit",
});

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const module = join(rust, "target", target, "release", "verified_native.wasm");
execFileSync(
  "wasm-bindgen",
  [module, "--target", "web", "--omit-default-module-path", "--out-dir", out, "--out-name", "glue"],
  { stdio: "inherit" },
);

const wasm = join(out, "glue_bg.wasm");
const bytes = readFileSync(wasm);
rmSync(wasm);
rmSync(join(out, "glue_bg.wasm.d.ts"), { force: true });
const notice = "// Generated by scripts/build-native.mjs. Do not edit.\n";
writeFileSync(
  join(out, "wasm.js"),
  `${notice}export const WASM_BASE64 =\n  "${bytes.toString("base64")}";\n`,
);
writeFileSync(join(out, "wasm.d.ts"), `${notice}export declare const WASM_BASE64: string;\n`);
console.log(`src/native: ${bytes.length} bytes of WebAssembly`);
